def vec(a_hex, b_hex):
    a = int(a_hex, 16)
    b = int(b_hex, 16)
    return {
        "a": a_hex,
        "b": b_hex,
        "dist": format(a ^ b, f'0{len(a_hex)}x'),
    }

# 256 бит = 64 hex-символа
vectors = [
    # 1. Совпадающие ID → расстояние 0
    vec("0"*64, "0"*64),
    # 2. Младший бит различается → расстояние 1
    vec("0"*64, "0"*63 + "1"),
    # 3. Старший бит различается → расстояние 2^255
    vec("8" + "0"*63, "0"*64),
    # 4. Все единицы XOR со всеми нулями → все единицы
    vec("f"*64, "0"*64),
    # 5. Произвольные разные ID
    vec("0123456789abcdef"*4, "fedcba9876543210"*4),
    # 6. Различие в середине
    vec("0"*32 + "a"*32, "0"*32 + "5"*32),
]
import json
print(json.dumps(vectors, indent=2))